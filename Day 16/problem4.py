def sum_of_numbers(nums):
    return sum(nums)
def maximum_of_numbers(nums):
    return max(nums)
def minimum_of_numbers(nums):
    return min(nums)
def average_of_numbers(nums):
    return sum_of_numbers(nums)/len(nums)

nums = [10, 25, 7, 40, 15]
print(sum_of_numbers(nums))
print(maximum_of_numbers(nums))
print(minimum_of_numbers(nums))
print(average_of_numbers(nums))
